def blosum62_score(reference_aa: str | None, target_aa: str | None) -> int | None:
    """Return the BLOSUM62 score, or ``None`` outside the canonical alphabet."""

    reference = _canonical_symbol(reference_aa)
    target = _canonical_symbol(target_aa)
    if reference is None or target is None:
        return None
    return _ROWS[_INDEX[reference]][_INDEX[target]]


def _canonical_symbol(amino_acid: str | None) -> str | None:
    if amino_acid is None:
        return None
    symbol = amino_acid.upper()
    return symbol if len(symbol) == 1 and symbol in CANONICAL_AMINO_ACIDS else None


